private void generarCaptcha() {
    int numero = random.nextInt(1_000_000);          // 0 a 999999
    codigoCaptcha = String.format("%06d", numero);   // siempre 6 dígitos

    // Separa los dígitos con espacios para que se lean mejor
    StringBuilder sb = new StringBuilder();
    for (int i = 0; i < codigoCaptcha.length(); i++) {
        sb.append(codigoCaptcha.charAt(i));
        if (i < codigoCaptcha.length() - 1) sb.append(' ');
    }
    lblCaptcha.setText(sb.toString());

    // Limpia el campo de captcha
    txtCaptcha.setText("");
}
private boolean validarCaptcha() {
    return txtCaptcha.getText().trim().equals(codigoCaptcha);
}
