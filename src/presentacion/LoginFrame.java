    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
       // 1) Capturar datos del formulario
    String usuario  = txtUsuario.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();
    String captcha  = txtCaptcha.getText().trim();

    // 2) Validar que no haya campos vacíos (NO regenera captcha)
    if (usuario.isEmpty() || password.isEmpty() || captcha.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Complete todos los campos, incluido el código.",
                "Campos incompletos",
                javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3) Validar captcha ANTES de consultar la BD
    if (!validarCaptcha()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "El código ingresado no es correcto.",
                "Código incorrecto",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        generarCaptcha();
        return;
    }

    // 4) Validar credenciales contra la base de datos
    entidad.Usuario u = loginNegocio.validar(usuario, password);

    if (u == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Usuario o contraseña incorrectos.",
                "Acceso denegado",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        generarCaptcha();
        txtPassword.setText("");
        return;
    }

    // 5) Credenciales correctas → guardar sesión
    config.SesionUsuario.setUsuario(u);

    // 6) Mostrar bienvenida
    javax.swing.JOptionPane.showMessageDialog(this,
            "Bienvenido, " + u.getNombreCompleto(),
            "Acceso concedido",
            javax.swing.JOptionPane.INFORMATION_MESSAGE);

    // 7) Redirigir según el ROL
    String rol = u.getRol();

    if ("ADMIN".equalsIgnoreCase(rol)) {
        new presentacion.MenuAdmin().setVisible(true);
    } else if ("MECANICO".equalsIgnoreCase(rol)) {
        new presentacion.MenuMecanico().setVisible(true);
    } else if ("EMPLEADO".equalsIgnoreCase(rol)) {
        new presentacion.MenuEmpleado().setVisible(true);
    } else {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Rol no reconocido: " + rol,
                "Error de configuración",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        config.SesionUsuario.cerrarSesion();
        generarCaptcha();
        return;
    }

    // 8) Cerrar el login
    this.dispose();
    }//GEN-LAST:event_btnIngresarActionPerformed

