    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Validar nombre
        if (txtNombre.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre del taller es obligatorio.");
            return;
        }

        // Validar RUC (11 dígitos si se ingresa)
        String ruc = txtRuc.getText().trim();
        if (!ruc.isEmpty() && !ruc.matches("\\d{11}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "El RUC debe tener 11 dígitos numéricos.");
            return;
        }

        // Validar IGV
        double igv;
        try {
            igv = Double.parseDouble(txtIgv.getText().trim().replace(",", "."));
            if (igv < 0 || igv > 50) throw new NumberFormatException();
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El IGV debe ser un número entre 0 y 50.");
            return;
        }

        // Cargar el registro actual para conservar ID y correlativo
        entidad.Configuracion c = configDAO.obtener();

        // Actualizar campos editables
        c.setNombreTaller(txtNombre.getText().trim());
        c.setRuc(ruc);
        c.setDireccion(txtDireccion.getText().trim());
        c.setTelefono(txtTelefono.getText().trim());
        c.setSerieBoleta(txtSerie.getText().trim());
        c.setIgvPorcentaje(igv);
        c.setMoneda(txtMoneda.getText().trim());

        if (configDAO.actualizar(c)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Configuración guardada correctamente.");
            cargarConfiguracion();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar la configuración.");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed


