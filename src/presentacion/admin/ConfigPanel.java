    private void cargarConfiguracion() {
        entidad.Configuracion c = configDAO.obtener();

        txtNombre.setText(c.getNombreTaller() != null ? c.getNombreTaller() : "");
        txtRuc.setText(c.getRuc() != null ? c.getRuc() : "");
        txtDireccion.setText(c.getDireccion() != null ? c.getDireccion() : "");
        txtTelefono.setText(c.getTelefono() != null ? c.getTelefono() : "");
        txtSerie.setText(c.getSerieBoleta() != null ? c.getSerieBoleta() : "B001");
        txtCorrel.setText(String.valueOf(c.getCorrelativoActual()));
        txtIgv.setText(String.format(java.util.Locale.US, "%.2f", c.getIgvPorcentaje()));
        txtMoneda.setText(c.getMoneda() != null ? c.getMoneda() : "S/");
    }
