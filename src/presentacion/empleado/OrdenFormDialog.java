private void prepararNuevaOrden() {
    txtId.setText("");
    txtNumero.setText(ordenDAO.obtenerSiguienteNumero());
    txtFecha.setText(new java.text.SimpleDateFormat("yyyy-MM-dd HH:mm").format(new java.util.Date()));
    txtProblema.setText("");
    txtDiagnostico.setText("");
    txtObservacion.setText("");

    if (cboCliente.getItemCount() > 0) cboCliente.setSelectedIndex(0);
    if (cboMecanico.getItemCount() > 0) cboMecanico.setSelectedIndex(0);
    cboEstado.setSelectedItem("PENDIENTE");

    itemsActuales.clear();
    refrescarTablaDetalle();
    actualizarTotal();

    txtProblema.requestFocus();
}

// ============================================================
// CARGAR ORDEN EN FORMULARIO
// ============================================================
private void cargarOrdenEnFormulario(entidad.OrdenTrabajo o) {
    txtId.setText(String.valueOf(o.getId()));
    txtNumero.setText(o.getNumeroOrden());
    txtFecha.setText(o.getFechaIngreso() != null ? o.getFechaIngreso() : "");
    txtProblema.setText(o.getDescripcionProblema() != null ? o.getDescripcionProblema() : "");
    txtDiagnostico.setText(o.getDiagnostico() != null ? o.getDiagnostico() : "");
    txtObservacion.setText(o.getObservacion() != null ? o.getObservacion() : "");
    cboEstado.setSelectedItem(o.getEstado());

    // Cliente
    for (int i = 0; i < clientesCombo.size(); i++) {
        if (clientesCombo.get(i).getId() == o.getClienteId()) {
            cboCliente.setSelectedIndex(i);
            break;
        }
    }

    // Vehículo (depende del cliente)
    cargarVehiculosDelCliente();
    for (int i = 0; i < vehiculosCombo.size(); i++) {
        if (vehiculosCombo.get(i).getId() == o.getVehiculoId()) {
            cboVehiculo.setSelectedIndex(i);
            break;
        }
    }

    // Mecánico
    for (int i = 0; i < mecanicosCombo.size(); i++) {
        entidad.Usuario u = mecanicosCombo.get(i);
        if (u != null && u.getId() == o.getMecanicoId()) {
            cboMecanico.setSelectedIndex(i);
            break;
        }
    }

    // Cargar detalle desde BD
    itemsActuales.clear();
    itemsActuales.addAll(detalleDAO.listarPorOrden(o.getId()));
    refrescarTablaDetalle();
    actualizarTotal();
}

// ============================================================
// CARGAR VEHÍCULOS SEGÚN CLIENTE
// ============================================================
private void cargarVehiculosDelCliente() {
    cboVehiculo.removeAllItems();
    vehiculosCombo.clear();

    int idx = cboCliente.getSelectedIndex();
    if (idx < 0) return;

    entidad.Cliente c = clientesCombo.get(idx);
    for (entidad.Vehiculo v : vehiculoDAO.listar()) {
        if (v.getClienteId() == c.getId()) {
            vehiculosCombo.add(v);
            cboVehiculo.addItem(v.getPlaca() + " - " + v.getMarca() + " " + v.getModelo());
        }
    }
}

// ============================================================
// REFRESCAR TABLA DE DETALLE
// ============================================================
private void refrescarTablaDetalle() {
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblDetalle.getModel();
    modelo.setRowCount(0);

    for (entidad.DetalleOrden d : itemsActuales) {
        modelo.addRow(new Object[]{
            d.getTipoItem(),
            d.getDescripcion(),
            d.getCantidad(),
            String.format("%.2f", d.getPrecioUnitario()),
            String.format("%.2f", d.getSubtotal())
        });
    }
}

// ============================================================
// ACTUALIZAR TOTAL
// ============================================================
private void actualizarTotal() {
    double total = 0;
    for (entidad.DetalleOrden d : itemsActuales) {
        total += d.getSubtotal();
    }
    lblTotal.setText(String.format("TOTAL: S/ %.2f", total));
}
