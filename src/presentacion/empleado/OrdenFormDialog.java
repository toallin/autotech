    private void btnAgregarItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarItemActionPerformed
        String tipo = (String) cboTipoItem.getSelectedItem();
    String descripcion = txtDescripcionItem.getText().trim();
    String cantStr = txtCantidad.getText().trim();

    // Validaciones básicas
    if (descripcion.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese una descripción.");
        return;
    }
    if (cantStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese la cantidad.");
        return;
    }

    int cantidad;
    try {
        cantidad = Integer.parseInt(cantStr);
        if (cantidad <= 0) throw new NumberFormatException();
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "La cantidad debe ser un número mayor a 0.");
        return;
    }

    // Precio: se toma del repuesto si es REPUESTO, o del campo si es MANO_OBRA
    double precio;

    if ("REPUESTO".equals(tipo)) {
        int idx = cboRepuesto.getSelectedIndex();
        if (idx < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un repuesto.");
            return;
        }
        // ✅ Precio directo del objeto Repuesto (sin parsing)
        precio = repuestosCombo.get(idx).getPrecioVenta();
    } else {
        // MANO_OBRA: leer del campo, forzando coma → punto si es necesario
        String precStr = txtPrecioItem.getText().trim().replace(",", ".");
        if (precStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el precio.");
            return;
        }
        try {
            precio = Double.parseDouble(precStr);
            if (precio < 0) throw new NumberFormatException();
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "El precio debe ser un número mayor o igual a 0.\nValor leído: '" + precStr + "'");
            return;
        }
    }

    // Construir ítem
    entidad.DetalleOrden d = new entidad.DetalleOrden();
    d.setTipoItem(tipo);
    d.setDescripcion(descripcion);
    d.setCantidad(cantidad);
    d.setPrecioUnitario(precio);
    d.calcularSubtotal();

    if ("REPUESTO".equals(tipo)) {
        int idx = cboRepuesto.getSelectedIndex();
        d.setRepuestoId(repuestosCombo.get(idx).getId());
    }

    itemsActuales.add(d);
    refrescarTablaDetalle();
    actualizarTotal();

    // Limpiar
    txtDescripcionItem.setText("");
    txtCantidad.setText("");
    txtPrecioItem.setText("");
    if ("REPUESTO".equals(tipo)) {
        cboRepuesto.setSelectedIndex(-1);
    }
    txtDescripcionItem.requestFocus();
    }//GEN-LAST:event_btnAgregarItemActionPerformed

    private void btnQuitarItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarItemActionPerformed
        int fila = tblDetalle.getSelectedRow();
    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un ítem para quitar.");
        return;
    }

    int r = javax.swing.JOptionPane.showConfirmDialog(this,
        "¿Quitar este ítem de la orden?", "Confirmar",
        javax.swing.JOptionPane.YES_NO_OPTION);

    if (r == javax.swing.JOptionPane.YES_OPTION) {
        itemsActuales.remove(fila);
        refrescarTablaDetalle();
        actualizarTotal();
    }
    }//GEN-LAST:event_btnQuitarItemActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
       // Validaciones
    if (cboCliente.getSelectedIndex() < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un cliente.");
        return;
    }
    if (cboVehiculo.getSelectedIndex() < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un vehículo.");
        return;
    }
    if (txtProblema.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese el problema reportado.");
        return;
    }
    if (itemsActuales.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Agregue al menos un ítem al detalle.");
        return;
    }

    // Calcular total
    double total = 0;
    for (entidad.DetalleOrden d : itemsActuales) {
        total += d.getSubtotal();
    }

    // Construir orden
    entidad.OrdenTrabajo o = new entidad.OrdenTrabajo();
    o.setNumeroOrden(txtNumero.getText());
    o.setClienteId(clientesCombo.get(cboCliente.getSelectedIndex()).getId());
    o.setVehiculoId(vehiculosCombo.get(cboVehiculo.getSelectedIndex()).getId());

    int idxMec = cboMecanico.getSelectedIndex();
    entidad.Usuario mec = (idxMec > 0) ? mecanicosCombo.get(idxMec) : null;
    o.setMecanicoId(mec != null ? mec.getId() : 0);

    o.setDescripcionProblema(txtProblema.getText().trim());
    o.setDiagnostico(txtDiagnostico.getText().trim());
    o.setEstado((String) cboEstado.getSelectedItem());
    o.setTotal(total);
    o.setObservacion(txtObservacion.getText().trim());
    o.setActivo(1);

    if (ordenActual == null) {
        // INSERTAR
        int id = ordenDAO.insertar(o);
        if (id <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo insertar la orden.");
            return;
        }
        // Insertar detalle
        for (entidad.DetalleOrden d : itemsActuales) {
            d.setOrdenId(id);
            detalleDAO.insertar(d);
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Orden registrada: " + o.getNumeroOrden());
    } else {
        // ACTUALIZAR
        o.setId(ordenActual.getId());
        o.setFechaEntrega(ordenActual.getFechaEntrega());
        if (!ordenDAO.actualizar(o)) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar la orden.");
            return;
        }
        // Borrar detalle anterior e insertar el nuevo
        detalleDAO.eliminarPorOrden(o.getId());
        for (entidad.DetalleOrden d : itemsActuales) {
            d.setOrdenId(o.getId());
            detalleDAO.insertar(d);
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Orden actualizada.");
    }

    dispose();
    }//GEN-LAST:event_btnGuardarActionPerformed

